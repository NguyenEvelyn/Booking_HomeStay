ALTER TABLE users ADD COLUMN IF NOT EXISTS address VARCHAR(255);

CREATE TABLE IF NOT EXISTS homestays (
  homestay_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  host_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
  name VARCHAR(200) NOT NULL,
  description TEXT NOT NULL,
  address_line VARCHAR(255) NOT NULL,
  ward VARCHAR(100) NOT NULL DEFAULT '',
  district VARCHAR(100) NOT NULL,
  province VARCHAR(100) NOT NULL,
  latitude NUMERIC(10,7),
  longitude NUMERIC(10,7),
  check_in_time TIME NOT NULL DEFAULT TIME '14:00',
  check_out_time TIME NOT NULL DEFAULT TIME '12:00',
  status VARCHAR(30) NOT NULL DEFAULT 'Draft'
    CHECK (status IN ('Draft','Pending','Approved','Rejected','Suspended')),
  rejection_reason VARCHAR(500),
  reviewed_by BIGINT REFERENCES users(user_id) ON DELETE SET NULL,
  reviewed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_homestays_host ON homestays(host_id);
CREATE INDEX IF NOT EXISTS ix_homestays_public_search ON homestays(status, province, district);

CREATE TABLE IF NOT EXISTS amenities (
  amenity_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL UNIQUE,
  icon_url VARCHAR(500),
  category VARCHAR(50) NOT NULL,
  description VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS room_types (
  room_type_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  homestay_id BIGINT NOT NULL REFERENCES homestays(homestay_id) ON DELETE CASCADE,
  name VARCHAR(150) NOT NULL,
  description TEXT NOT NULL,
  base_price NUMERIC(18,2) NOT NULL CHECK (base_price > 0),
  max_adults INTEGER NOT NULL CHECK (max_adults > 0),
  max_children INTEGER NOT NULL DEFAULT 0 CHECK (max_children >= 0),
  bed_type VARCHAR(100) NOT NULL,
  room_size NUMERIC(8,2) CHECK (room_size IS NULL OR room_size > 0),
  status VARCHAR(20) NOT NULL DEFAULT 'Active' CHECK (status IN ('Active','Inactive')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE(homestay_id, name)
);
CREATE INDEX IF NOT EXISTS ix_room_types_homestay ON room_types(homestay_id);

CREATE TABLE IF NOT EXISTS rooms (
  room_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  room_type_id BIGINT NOT NULL REFERENCES room_types(room_type_id) ON DELETE RESTRICT,
  room_number VARCHAR(30) NOT NULL,
  floor_number INTEGER,
  status VARCHAR(30) NOT NULL DEFAULT 'Available'
    CHECK (status IN ('Available','Occupied','Cleaning','Maintenance','Inactive')),
  note VARCHAR(500),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE(room_type_id, room_number)
);
CREATE INDEX IF NOT EXISTS ix_rooms_type_status ON rooms(room_type_id, status);

CREATE TABLE IF NOT EXISTS homestay_amenities (
  homestay_id BIGINT NOT NULL REFERENCES homestays(homestay_id) ON DELETE CASCADE,
  amenity_id INTEGER NOT NULL REFERENCES amenities(amenity_id) ON DELETE CASCADE,
  PRIMARY KEY(homestay_id, amenity_id)
);

CREATE TABLE IF NOT EXISTS room_type_amenities (
  room_type_id BIGINT NOT NULL REFERENCES room_types(room_type_id) ON DELETE CASCADE,
  amenity_id INTEGER NOT NULL REFERENCES amenities(amenity_id) ON DELETE CASCADE,
  PRIMARY KEY(room_type_id, amenity_id)
);

CREATE TABLE IF NOT EXISTS homestay_images (
  image_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  homestay_id BIGINT NOT NULL REFERENCES homestays(homestay_id) ON DELETE CASCADE,
  image_url VARCHAR(500) NOT NULL,
  caption VARCHAR(255),
  is_thumbnail BOOLEAN NOT NULL DEFAULT FALSE,
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_homestay_images_homestay ON homestay_images(homestay_id);

CREATE TABLE IF NOT EXISTS room_type_images (
  image_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  room_type_id BIGINT NOT NULL REFERENCES room_types(room_type_id) ON DELETE CASCADE,
  image_url VARCHAR(500) NOT NULL,
  caption VARCHAR(255),
  is_thumbnail BOOLEAN NOT NULL DEFAULT FALSE,
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_room_type_images_type ON room_type_images(room_type_id);

CREATE TABLE IF NOT EXISTS room_images (
  image_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  room_id BIGINT NOT NULL REFERENCES rooms(room_id) ON DELETE CASCADE,
  image_url VARCHAR(500) NOT NULL,
  caption VARCHAR(255),
  is_thumbnail BOOLEAN NOT NULL DEFAULT FALSE,
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_room_images_room ON room_images(room_id);

