CREATE TABLE IF NOT EXISTS room_price_periods (
  price_period_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  room_type_id BIGINT NOT NULL REFERENCES room_types(room_type_id) ON DELETE CASCADE,
  name VARCHAR(100) NOT NULL,
  start_date DATE NOT NULL,
  end_date DATE NOT NULL,
  price_per_night NUMERIC(18,2) NOT NULL CHECK (price_per_night > 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (end_date >= start_date)
);
CREATE INDEX IF NOT EXISTS ix_room_price_periods_room_dates ON room_price_periods(room_type_id,start_date,end_date);

CREATE TABLE IF NOT EXISTS bookings (
  booking_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_code VARCHAR(30) NOT NULL UNIQUE,
  customer_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
  homestay_id BIGINT NOT NULL REFERENCES homestays(homestay_id) ON DELETE RESTRICT,
  check_in_date DATE NOT NULL,
  check_out_date DATE NOT NULL,
  adult_count INTEGER NOT NULL CHECK (adult_count > 0),
  child_count INTEGER NOT NULL DEFAULT 0 CHECK (child_count >= 0),
  subtotal NUMERIC(18,2) NOT NULL CHECK (subtotal >= 0),
  discount_amount NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (discount_amount >= 0),
  service_fee NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (service_fee >= 0),
  tax_amount NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (tax_amount >= 0),
  total_amount NUMERIC(18,2) NOT NULL CHECK (total_amount >= 0),
  status VARCHAR(30) NOT NULL DEFAULT 'PendingPayment'
    CHECK (status IN ('PendingPayment','Confirmed','CheckedIn','Completed','CancellationRequested','Cancelled','Expired','PaymentFailed')),
  customer_note VARCHAR(500),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK(check_out_date > check_in_date)
);
CREATE INDEX IF NOT EXISTS ix_bookings_customer ON bookings(customer_id, created_at DESC);
CREATE INDEX IF NOT EXISTS ix_bookings_inventory ON bookings(homestay_id, check_in_date, check_out_date, status);

CREATE TABLE IF NOT EXISTS booking_details (
  booking_detail_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id BIGINT NOT NULL REFERENCES bookings(booking_id) ON DELETE CASCADE,
  room_type_id BIGINT NOT NULL REFERENCES room_types(room_type_id) ON DELETE RESTRICT,
  room_id BIGINT REFERENCES rooms(room_id) ON DELETE RESTRICT,
  quantity INTEGER NOT NULL DEFAULT 1 CHECK (quantity > 0),
  price_per_night NUMERIC(18,2) NOT NULL CHECK (price_per_night >= 0),
  number_of_nights INTEGER NOT NULL CHECK (number_of_nights > 0),
  extra_fee NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (extra_fee >= 0),
  line_total NUMERIC(18,2) NOT NULL CHECK (line_total >= 0),
  guest_name VARCHAR(100),
  note VARCHAR(500)
);
CREATE INDEX IF NOT EXISTS ix_booking_details_room_schedule ON booking_details(room_id, booking_id);
CREATE INDEX IF NOT EXISTS ix_booking_details_type ON booking_details(room_type_id, booking_id);

CREATE TABLE IF NOT EXISTS payments (
  payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id BIGINT NOT NULL REFERENCES bookings(booking_id) ON DELETE RESTRICT,
  transaction_code VARCHAR(100) NOT NULL UNIQUE,
  payment_method VARCHAR(30) NOT NULL,
  transaction_type VARCHAR(20) NOT NULL CHECK (transaction_type IN ('Payment','Refund')),
  amount NUMERIC(18,2) NOT NULL CHECK (amount >= 0),
  status VARCHAR(30) NOT NULL DEFAULT 'Pending' CHECK (status IN ('Pending','Success','Failed')),
  paid_at TIMESTAMPTZ,
  gateway_response TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_payments_booking ON payments(booking_id, transaction_type, status);

CREATE TABLE IF NOT EXISTS reviews (
  review_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id BIGINT NOT NULL UNIQUE REFERENCES bookings(booking_id) ON DELETE RESTRICT,
  customer_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
  homestay_id BIGINT NOT NULL REFERENCES homestays(homestay_id) ON DELETE RESTRICT,
  rating INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
  comment VARCHAR(1000),
  host_reply VARCHAR(1000),
  host_replied_at TIMESTAMPTZ,
  status VARCHAR(20) NOT NULL DEFAULT 'Visible' CHECK (status IN ('Visible','Hidden')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_reviews_homestay ON reviews(homestay_id, status, created_at DESC);

CREATE TABLE IF NOT EXISTS cancellations (
  cancellation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id BIGINT NOT NULL UNIQUE REFERENCES bookings(booking_id) ON DELETE RESTRICT,
  cancelled_by BIGINT NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
  reason VARCHAR(500) NOT NULL,
  cancelled_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  cancellation_fee NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (cancellation_fee >= 0),
  refund_amount NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (refund_amount >= 0),
  status VARCHAR(30) NOT NULL DEFAULT 'Requested' CHECK (status IN ('Requested','Approved','Rejected','Refunded')),
  processed_by BIGINT REFERENCES users(user_id) ON DELETE SET NULL,
  processed_at TIMESTAMPTZ
);
