-- Chạy sau database/demo-homestays.sql hoặc dùng schema đầy đủ postgres-homestay-database.sql.
CREATE TABLE IF NOT EXISTS bookings (
  booking_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, booking_code VARCHAR(30) NOT NULL UNIQUE,
  customer_id BIGINT NOT NULL REFERENCES users, homestay_id BIGINT NOT NULL REFERENCES homestays,
  check_in_date DATE NOT NULL, check_out_date DATE NOT NULL, adult_count INT NOT NULL, child_count INT NOT NULL DEFAULT 0,
  subtotal NUMERIC(18,2) NOT NULL, discount_amount NUMERIC(18,2) NOT NULL DEFAULT 0, service_fee NUMERIC(18,2) NOT NULL DEFAULT 0,
  tax_amount NUMERIC(18,2) NOT NULL DEFAULT 0, total_amount NUMERIC(18,2) NOT NULL,
  status VARCHAR(30) NOT NULL DEFAULT 'PendingPayment', customer_note VARCHAR(500),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK(check_out_date > check_in_date)
);
CREATE TABLE IF NOT EXISTS booking_details (
  booking_detail_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, booking_id BIGINT NOT NULL REFERENCES bookings ON DELETE CASCADE,
  room_type_id BIGINT NOT NULL REFERENCES room_types, room_id BIGINT REFERENCES rooms,
  price_per_night NUMERIC(18,2) NOT NULL, number_of_nights INT NOT NULL, extra_fee NUMERIC(18,2) NOT NULL DEFAULT 0,
  line_total NUMERIC(18,2) NOT NULL, guest_name VARCHAR(100), note VARCHAR(500)
);
CREATE TABLE IF NOT EXISTS payments (
  payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, booking_id BIGINT NOT NULL REFERENCES bookings,
  transaction_code VARCHAR(100) NOT NULL UNIQUE, payment_method VARCHAR(30) NOT NULL, transaction_type VARCHAR(20) NOT NULL,
  amount NUMERIC(18,2) NOT NULL, status VARCHAR(30) NOT NULL DEFAULT 'Pending', paid_at TIMESTAMPTZ, gateway_response TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
