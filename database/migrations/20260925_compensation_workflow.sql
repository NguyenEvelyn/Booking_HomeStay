BEGIN;

CREATE TABLE IF NOT EXISTS compensation_catalog_items (
  catalog_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  homestay_id BIGINT NOT NULL REFERENCES homestays(homestay_id) ON DELETE CASCADE,
  name VARCHAR(150) NOT NULL,
  category VARCHAR(50) NOT NULL,
  description VARCHAR(500),
  unit VARCHAR(30) NOT NULL DEFAULT 'item',
  replacement_cost NUMERIC(18,2) NOT NULL CHECK (replacement_cost > 0),
  maximum_compensation NUMERIC(18,2) NOT NULL CHECK (maximum_compensation > 0 AND maximum_compensation <= replacement_cost),
  default_depreciation_percent NUMERIC(5,2) NOT NULL DEFAULT 0 CHECK (default_depreciation_percent BETWEEN 0 AND 100),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  effective_from TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_by BIGINT NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_compensation_catalog_homestay_active ON compensation_catalog_items(homestay_id,is_active);

CREATE TABLE IF NOT EXISTS compensation_claims (
  claim_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id BIGINT NOT NULL REFERENCES bookings(booking_id) ON DELETE RESTRICT,
  status VARCHAR(30) NOT NULL,
  incident_type VARCHAR(40) NOT NULL,
  description VARCHAR(2000) NOT NULL,
  incident_at TIMESTAMPTZ NOT NULL,
  requested_amount NUMERIC(18,2) NOT NULL DEFAULT 0,
  approved_amount NUMERIC(18,2),
  response_due_at TIMESTAMPTZ,
  submitted_at TIMESTAMPTZ,
  confirmed_at TIMESTAMPTZ,
  created_by BIGINT NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
  additional_charge_id BIGINT UNIQUE REFERENCES additional_charges(additional_charge_id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_compensation_claim_booking_status ON compensation_claims(booking_id,status);
CREATE INDEX IF NOT EXISTS ix_compensation_claim_status_updated ON compensation_claims(status,updated_at DESC);

CREATE TABLE IF NOT EXISTS compensation_claim_items (
  claim_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  claim_id BIGINT NOT NULL REFERENCES compensation_claims(claim_id) ON DELETE CASCADE,
  catalog_item_id BIGINT REFERENCES compensation_catalog_items(catalog_item_id) ON DELETE SET NULL,
  item_name VARCHAR(150) NOT NULL,
  category VARCHAR(50) NOT NULL,
  damage_level VARCHAR(20) NOT NULL,
  quantity INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 100),
  unit_amount NUMERIC(18,2) NOT NULL CHECK (unit_amount > 0),
  depreciation_percent NUMERIC(5,2) NOT NULL CHECK (depreciation_percent BETWEEN 0 AND 100),
  requested_amount NUMERIC(18,2) NOT NULL CHECK (requested_amount >= 0),
  note VARCHAR(500)
);

CREATE TABLE IF NOT EXISTS compensation_evidence (
  evidence_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  claim_id BIGINT NOT NULL REFERENCES compensation_claims(claim_id) ON DELETE CASCADE,
  url VARCHAR(1000) NOT NULL,
  media_type VARCHAR(20) NOT NULL CHECK (media_type IN ('image','video','document')),
  caption VARCHAR(500),
  uploaded_by BIGINT NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMIT;
